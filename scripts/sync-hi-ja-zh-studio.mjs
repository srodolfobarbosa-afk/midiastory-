function parseStringsXml(filePath) {
  const xml = fs.readFileSync(filePath, "utf8");
  const map = new Map();
  const regex = /<string\s+name="([^"]+)"([^>]*)>([\s\S]*?)<\/string>/g;
  let m;
  while ((m = regex.exec(xml)) !== null) {
    map.set(m[1], { attrs: m[2] || "", value: m[3] });
  }
  return map;
}

function escapeXmlValue(str) {
  return str
    .replace(/&(?!amp;|lt;|gt;|quot;|apos;)/g, "&amp;")
    .replace(/(?<!\\)'/g, "\\'")
    .replace(/\n/g, "\\n");
}

const dirMap = { hi: "values-hi", ja: "values-ja", zh: "values-zh-rCN" };

for (const [lang, dir] of Object.entries(dirMap)) {
  const filePath = path.join(RES_DIR, dir, "strings.xml");
  const existing = parseStringsXml(filePath);
  const patch = extraTranslations[lang];
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"];
  for (const [key, entry] of existing.entries()) {
    const val = patch[key] !== undefined ? escapeXmlValue(patch[key]) : entry.value;
    lines.push(`    <string name="${key}"${entry.attrs}>${val}</string>`);
  }
  lines.push("</resources>", "");
  fs.writeFileSync(filePath, lines.join("\n"), "utf8");
  console.log(`Updated ${dir}/strings.xml with ${Object.keys(patch).length} native Studio/WA strings`);
}
