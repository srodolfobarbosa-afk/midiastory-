function escapeXml(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
}

function upsertKeysInXml(xmlText, additions) {
  let out = xmlText;
  for (const [key, val] of Object.entries(additions)) {
    const escaped = escapeXml(val);
    const line = `    <string name="${key}">${escaped}</string>`;
    const regex = new RegExp(`^\\s*<string name="${key}"[^>]*>[\\s\\S]*?<\\/string>`, "m");
    if (regex.test(out)) {
      out = out.replace(regex, line);
    } else {
      out = out.replace(/<\/resources>\s*$/, `${line}\n</resources>\n`);
    }
  }
  return out;
}

