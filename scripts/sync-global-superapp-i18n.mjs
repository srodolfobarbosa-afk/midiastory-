// 2. Build complete strings.xml for ar, ru, in, bn, ko based on updated base values/strings.xml + English/PT key coverage
const baseXml = fs.readFileSync(path.join(RES_DIR, "values/strings.xml"), "utf8");
const baseEntries = parseStringsXml(baseXml);
const enXml = fs.readFileSync(path.join(RES_DIR, "values-en/strings.xml"), "utf8");
const enMap = Object.fromEntries(parseStringsXml(enXml).map((e) => [e.key, e.rawValue]));

for (const [locCode, trMap] of Object.entries(coreTranslationsByNewLocale)) {
  const folder = `values-${locCode}`;
  const outDir = path.join(RES_DIR, folder);
  fs.mkdirSync(outDir, { recursive: true });
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"];
  for (const { key, attrs, rawValue } of baseEntries) {
    if (Object.prototype.hasOwnProperty.call(trMap, key)) {
      lines.push(`    <string name="${key}"${attrs}>${escapeXml(trMap[key])}</string>`);
    } else {
      lines.push(`    <string name="${key}"${attrs}>${enMap[key] ?? rawValue}</string>`);
    }
  }
  lines.push("</resources>\n");
  fs.writeFileSync(path.join(outDir, "strings.xml"), lines.join("\n"), "utf8");
  console.log(`Generated complete ${folder}/strings.xml (${baseEntries.length} total keys, ${Object.keys(trMap).length} native ${locCode} overrides)`);
}
