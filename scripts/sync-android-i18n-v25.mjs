function escapeXmlValue(str) {
  return str
    .replace(/&(?!amp;|lt;|gt;|quot;|apos;)/g, "&amp;")
    .replace(/(?<!\\)'/g, "\\'")
    .replace(/\n/g, "\\n");
}

