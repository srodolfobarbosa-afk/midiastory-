create extension if not exists vector with schema extensions;

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  content text not null,
  embedding extensions.vector(1536),
  created_at timestamptz not null default now()
);

create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.memories (
  id bigint generated by default as identity primary key,
  content text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.mobile_backups (
  id bigint generated by default as identity primary key,
  device text not null,
  source_path text not null,
  backup_path text not null,
  created_at timestamptz not null default now()
);

alter table public.documents enable row level security;
alter table public.conversations enable row level security;
alter table public.memories enable row level security;
alter table public.mobile_backups enable row level security;

create policy "service_role_full_access_documents" on public.documents for all to service_role using (true) with check (true);
create policy "service_role_full_access_conversations" on public.conversations for all to service_role using (true) with check (true);
create policy "service_role_full_access_memories" on public.memories for all to service_role using (true) with check (true);
create policy "service_role_full_access_mobile_backups" on public.mobile_backups for all to service_role using (true) with check (true);

create or replace function public.match_documents(query_embedding extensions.vector(1536), match_count int default 5)
returns table (id bigint, content text, similarity float)
language sql stable
as $$
  select d.id, d.content, 1 - (d.embedding <=> query_embedding) as similarity
  from public.documents d
  where d.embedding is not null
  order by d.embedding <=> query_embedding
  limit greatest(1, least(match_count, 20));
$$;

revoke all on function public.match_documents(extensions.vector, int) from public, anon, authenticated;
grant execute on function public.match_documents(extensions.vector, int) to service_role;
